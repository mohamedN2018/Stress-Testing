"""Optional k6 backend for load tests (subprocess, JSON output stream).

The generated script carries the run's limits (VUs, stages, global ``rps``
cap, no redirects); the application counts every request from k6's JSON
output and kills the process when the budget or any stop condition is hit.
"""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path
from typing import Any

from ... import USER_AGENT
from ...core.config import Settings
from ...core.models import EngineOutcome, Finding, Severity
from ...engines.base import EngineContext
from ..process import RequestEvent, run_external_tool

SCRIPT_TEMPLATE = """\
// Generated by Sentinel Test Lab. Limits come from the authorized run configuration.
import http from 'k6/http';
import { sleep } from 'k6';

const cfg = __CONFIG__;

export const options = {
  scenarios: {
    main: {
      executor: 'ramping-vus',
      startVUs: 0,
      stages: cfg.stages,
      gracefulRampDown: '0s',
      gracefulStop: '1s',
    },
  },
  rps: cfg.rps,
  maxRedirects: 0,
  insecureSkipTLSVerify: cfg.insecure,
  userAgent: cfg.userAgent,
  summaryTrendStats: ['avg', 'p(95)'],
};

export default function () {
  const path = cfg.paths[__ITER % cfg.paths.length];
  http.request(cfg.method, cfg.baseUrl + path, null, { timeout: cfg.timeout });
  if (cfg.interval > 0) {
    sleep(cfg.interval);
  }
}
"""


def find_k6(settings: Settings) -> list[str] | None:
    if settings.k6_path and Path(settings.k6_path).is_file():
        return [settings.k6_path]
    found = shutil.which("k6")
    if found:
        return [found]
    # A freshly installed k6 is not on the PATH of already-running programs: check the default location.
    for base in (os.environ.get("ProgramFiles"), os.environ.get("ProgramFiles(x86)")):
        candidate = Path(base) / "k6" / "k6.exe" if base else None
        if candidate is not None and candidate.is_file():
            return [str(candidate)]
    return None


def build_script(ctx: EngineContext) -> str:
    config = ctx.config
    ramp = max(0.0, min(config.ramp_up_s, config.duration_s))
    stages = []
    if ramp > 0:
        stages.append({"duration": f"{ramp:g}s", "target": config.users})
    else:
        stages.append({"duration": "1s", "target": config.users})
        ramp = 1.0
    hold = config.duration_s - ramp
    if hold > 0:
        stages.append({"duration": f"{hold:g}s", "target": config.users})
    cfg = {
        "stages": stages,
        "rps": max(1, int(config.rate_limit_rps)),
        "insecure": not ctx.target.verify_tls,
        "userAgent": USER_AGENT,
        "paths": config.paths or ["/"],
        "method": config.method,
        "baseUrl": ctx.target.base_url,
        "timeout": f"{config.timeout_s:g}s",
        "interval": config.interval_s,
    }
    return SCRIPT_TEMPLATE.replace("__CONFIG__", json.dumps(cfg, ensure_ascii=False))


def parse_k6_event(event: dict[str, Any]) -> tuple[str, Any] | None:
    """Translate one k6 JSON line into ('request', RequestEvent) or ('users', n)."""
    if event.get("type") != "Point":
        return None
    data = event.get("data") or {}
    metric = event.get("metric")
    if metric == "vus":
        return "users", int(data.get("value", 0))
    if metric != "http_req_duration":
        return None
    tags = data.get("tags") or {}
    try:
        status = int(tags.get("status", 0)) or None
    except (TypeError, ValueError):
        status = None
    error = tags.get("error") if status is None else None
    return "request", (status, float(data.get("value", 0.0)), (error or "error")[:40] if status is None else None)


class K6LoadEngine:
    def __init__(self, command: list[str] | None = None) -> None:
        self._command = command  # injectable for tests

    async def run(self, ctx: EngineContext) -> EngineOutcome:
        command = self._command or find_k6(ctx.settings)
        if command is None:
            raise RuntimeError("k6 غير مثبت أو غير موجود في PATH.")
        script = ctx.work_dir / "sentinel_k6_script.js"
        script.write_text(build_script(ctx), encoding="utf-8")
        events_path = ctx.work_dir / "k6_events.ndjson"
        args = [*command, "run", "--quiet", "--out", f"json={events_path}", str(script)]

        def handle(event: dict[str, Any]) -> RequestEvent | None:
            parsed = parse_k6_event(event)
            if parsed is None:
                return None
            kind, value = parsed
            if kind == "users":
                ctx.metrics.set_users(value)
                return None
            return value

        ctx.metrics.set_phase("k6")
        ctx.emit(f"تشغيل k6: {ctx.config.users} مستخدم لمدة {ctx.config.duration_s:g} ث")
        exit_code = await run_external_tool(ctx, args, {}, events_path, handle, ctx.work_dir / "k6_output.log")
        findings: list[Finding] = []
        if ctx.metrics.total == 0:
            findings.append(Finding(
                Severity.INFO, "integration", "k6 لم يسجّل أي طلب",
                f"راجع السجل: {ctx.work_dir / 'k6_output.log'}"))
        return EngineOutcome(findings, {"backend": "k6", "exit_code": exit_code,
                                        "phases": ctx.metrics.all_phases()})
