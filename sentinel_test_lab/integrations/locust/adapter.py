"""Optional Locust backend for load tests (headless subprocess).

The generated locustfile enforces the run's limits itself (user count, run
time, per-user throughput, request budget); the application additionally
counts every request and kills the process on any stop condition.
"""

from __future__ import annotations

import importlib.util
import json
import shutil
import sys
from pathlib import Path
from typing import Any

from ... import USER_AGENT
from ...core.config import Settings
from ...core.models import EngineOutcome, Finding, Severity
from ...engines.base import EngineContext
from ..process import RequestEvent, run_external_tool

LOCUSTFILE = '''\
"""Generated by Sentinel Test Lab. Limits come from the authorized run configuration."""
import json
import os

import gevent
from locust import HttpUser, constant_throughput, events, task

OUT = open(os.environ["SENTINEL_EVENTS"], "a", buffering=1, encoding="utf-8")
PATHS = json.loads(os.environ["SENTINEL_PATHS"])
METHOD = os.environ["SENTINEL_METHOD"]
BUDGET = int(os.environ["SENTINEL_BUDGET"])
PER_USER_RATE = float(os.environ["SENTINEL_PER_USER_RATE"])
TIMEOUT = float(os.environ["SENTINEL_TIMEOUT"])
VERIFY = os.environ.get("SENTINEL_VERIFY", "1") == "1"
USER_AGENT = os.environ["SENTINEL_USER_AGENT"]
_sent = 0


class SentinelUser(HttpUser):
    wait_time = constant_throughput(PER_USER_RATE)

    def on_start(self):
        self.client.verify = VERIFY
        self.client.trust_env = False
        self.client.headers["User-Agent"] = USER_AGENT

    @task
    def hit(self):
        global _sent
        if _sent >= BUDGET:
            self.environment.runner.quit()
            return
        _sent += 1
        path = PATHS[_sent % len(PATHS)]
        self.client.request(METHOD, path, name=path, allow_redirects=False, timeout=TIMEOUT)


@events.request.add_listener
def on_request(request_type, name, response_time, response_length, response=None, exception=None, **kwargs):
    status = getattr(response, "status_code", 0) or None
    error = type(exception).__name__ if exception is not None and status is None else None
    OUT.write(json.dumps({"type": "request", "status": status, "ms": response_time, "error": error}) + "\\n")


@events.init.add_listener
def on_init(environment, **kwargs):
    def report_users():
        while True:
            runner = environment.runner
            if runner is not None:
                OUT.write(json.dumps({"type": "users", "n": runner.user_count}) + "\\n")
            gevent.sleep(1)

    gevent.spawn(report_users)
'''


def find_locust(settings: Settings) -> list[str] | None:
    """Command prefix that launches Locust, or None when it is not installed."""
    if settings.locust_path and Path(settings.locust_path).is_file():
        return [settings.locust_path]
    found = shutil.which("locust")
    if found:
        return [found]
    if not getattr(sys, "frozen", False) and importlib.util.find_spec("locust") is not None:
        return [sys.executable, "-m", "locust"]
    return None


class LocustLoadEngine:
    async def run(self, ctx: EngineContext) -> EngineOutcome:
        config = ctx.config
        command = find_locust(ctx.settings)
        if command is None:
            raise RuntimeError("Locust غير مثبت أو غير موجود في PATH.")
        locustfile = ctx.work_dir / "sentinel_locustfile.py"
        locustfile.write_text(LOCUSTFILE, encoding="utf-8")
        events_path = ctx.work_dir / "locust_events.ndjson"
        spawn_rate = config.users / config.ramp_up_s if config.ramp_up_s > 0 else config.users
        interval_rate = 1.0 / config.interval_s if config.interval_s > 0 else float("inf")
        per_user_rate = min(config.rate_limit_rps / config.users, interval_rate)
        args = [
            *command, "-f", str(locustfile), "--headless",
            "-u", str(config.users), "-r", f"{max(spawn_rate, 0.1):.3f}",
            "-t", f"{max(1, int(config.duration_s))}s",
            "--host", ctx.target.base_url, "--stop-timeout", "1",
        ]
        env = {
            "SENTINEL_EVENTS": str(events_path),
            "SENTINEL_PATHS": json.dumps(config.paths or ["/"]),
            "SENTINEL_METHOD": config.method,
            "SENTINEL_BUDGET": str(ctx.guard.budget),
            "SENTINEL_PER_USER_RATE": f"{per_user_rate:.6f}",
            "SENTINEL_TIMEOUT": str(config.timeout_s),
            "SENTINEL_VERIFY": "1" if ctx.target.verify_tls else "0",
            "SENTINEL_USER_AGENT": USER_AGENT,
        }

        def handle(event: dict[str, Any]) -> RequestEvent | None:
            if event.get("type") == "users":
                ctx.metrics.set_users(int(event.get("n", 0)))
                return None
            if event.get("type") != "request":
                return None
            return event.get("status"), float(event.get("ms") or 0.0), event.get("error")

        ctx.metrics.set_phase("locust")
        ctx.emit(f"تشغيل Locust: {config.users} مستخدم لمدة {config.duration_s:g} ث")
        exit_code = await run_external_tool(
            ctx, args, env, events_path, handle, ctx.work_dir / "locust_output.log"
        )
        findings: list[Finding] = []
        if ctx.metrics.total == 0:
            findings.append(Finding(
                Severity.INFO, "integration", "Locust لم يسجّل أي طلب",
                f"راجع السجل: {ctx.work_dir / 'locust_output.log'}"))
        return EngineOutcome(findings, {"backend": "locust", "exit_code": exit_code,
                                        "phases": ctx.metrics.all_phases()})
